function at(now: number, minutes: number): string {
  return new Date(now + minutes * 60_000).toISOString();
}

function makeTracks(
  venueId: string,
  indexes: number[],
  priceBase: number,
  disabledAt: number[] = [],
  brokenAt: number[] = [],
): Track[] {
  return indexes.map((catalogIndex, index) => {
    const item = CATALOG[catalogIndex];
    if (!item) throw new Error(`Нет трека каталога ${catalogIndex}`);
    const [title, artist, genre, durationSec, hue] = item;
    return {
      id: `trk_${venueId}_${index}`,
      venueId,
      title,
      artist,
      genre,
      durationSec,
      priceKzt: priceBase + (index % 5) * 500,
      enabled: !disabledAt.includes(index),
      coverHue: hue,
      coverUrl: brokenAt.includes(index) ? BROKEN_COVER_URL : undefined,
    };
  });
}

function take(tracks: Track[], index: number): Track {
  const track = tracks[index];
  if (!track) throw new Error(`Нет трека ${index}`);
  return track;
}

interface RequestSeed {
  id: string;
  venueId: string;
  track: Track;
  guestName: string;
  tableLabel: string;
  note: string;
  amountKzt: number;
  status: MusicRequest["status"];
  paymentStatus: MusicRequest["paymentStatus"];
  mode: MusicRequest["mode"];
  createdAt: string;
  updatedAt: string;
  expiresAt: string;
  decisionCode: MusicRequest["decisionCode"];
}

function toRequest(seed: RequestSeed): MusicRequest {
  return {
    id: seed.id,
    venueId: seed.venueId,
    trackId: seed.track.id,
    trackTitle: seed.track.title,
    trackArtist: seed.track.artist,
    coverHue: seed.track.coverHue,
    coverUrl: seed.track.coverUrl,
    guestName: seed.guestName,
    tableLabel: seed.tableLabel,
    note: seed.note,
    amountKzt: seed.amountKzt,
    status: seed.status,
    paymentStatus: seed.paymentStatus,
    mode: seed.mode,
    createdAt: seed.createdAt,
    updatedAt: seed.updatedAt,
    expiresAt: seed.expiresAt,
    decisionCode: seed.decisionCode,
  };
}

